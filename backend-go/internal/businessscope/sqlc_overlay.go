package businessscope

import (
	"fmt"
	"sort"
	"strings"
)

// SQLCOwnershipOverlay describes the columns added dynamically by migration 8.
// It is only a sqlc parser input; it is not a migration or a schema authority.
func SQLCOwnershipOverlay() string {
	names := make([]string, 0, len(OwnedTables))
	for _, table := range OwnedTables {
		names = append(names, table.Name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("-- Generated by go run ./cmd/sqlcscope; do not execute as a migration.\n")
	for _, name := range names {
		fmt.Fprintf(&b, "ALTER TABLE %s ADD COLUMN business_id uuid NOT NULL;\n", name)
	}
	return b.String()
}
