<script setup lang="ts">
import AppIcon from "@/components/AppIcon.vue";
import { computed } from "vue";
import { useRoute, useRouter } from "vue-router";
import { useQuery, useMutation, useQueryClient } from "@tanstack/vue-query";
import DataTable from "primevue/datatable";
import Column from "primevue/column";
import Button from "primevue/button";
import Tag from "primevue/tag";
import PageHeader from "@/components/PageHeader.vue";
import EmptyState from "@/components/EmptyState.vue";
import { api } from "@/api/client";
import { formatAmount } from "@/utils/money";

interface Customer {
  customer_id: string;
  name: string;
}

interface Invoice {
  invoice_id: string;
  customer_id: string;
  invoice_type: string;
  invoice_number: string | null;
  currency: string;
  amount: string;
  balance_due: string;
  status: string;
  issue_date: string;
  due_date: string;
  created_at: string;
}

const queryClient = useQueryClient();
const router = useRouter();
const route = useRoute();

const { data: customers } = useQuery<Customer[]>({
  queryKey: ["customers"],
  queryFn: async () => (await api.get<Customer[]>("/customers")).data,
});

const customerNameById = computed(() => {
  const map: Record<string, string> = {};
  for (const c of customers.value ?? []) map[c.customer_id] = c.name;
  return map;
});

function openInvoice(id: string) {
  router.push({ path: `/invoices/${id}/edit`, query: { from: route.fullPath } });
}

const { data, isLoading } = useQuery<Invoice[]>({
  queryKey: ["awaiting-finalization"],
  queryFn: async () => (await api.get<Invoice[]>("/invoices/awaiting-finalization")).data,
});

const finalize = useMutation({
  mutationFn: (id: string) => api.post(`/invoices/${id}/finalize`),
  onSuccess: () => queryClient.invalidateQueries({ queryKey: ["awaiting-finalization"] }),
});

const voidInvoice = useMutation({
  mutationFn: (id: string) =>
    api.post(`/invoices/${id}/void`, { reason: "voided from finalization queue" }),
  onSuccess: () => queryClient.invalidateQueries({ queryKey: ["awaiting-finalization"] }),
});
</script>

<template>
  <section>
    <PageHeader eyebrow="05 / Operations" title="Awaiting Finalization">
      <template #lede>
        <code>DRAFT</code> invoices generated by the scheduler or manual actions. Finalize to issue
        (status becomes <code>OPEN</code>; emailing marks it <code>SENT</code>).
      </template>
    </PageHeader>

    <DataTable
      :value="data ?? []"
      :loading="isLoading"
      data-key="invoice_id"
      striped-rows
      selection-mode="single"
      @row-click="(ev) => openInvoice((ev.data as Invoice).invoice_id)"
    >
      <template #empty>
        <EmptyState icon="circle-check" title="Queue is clear" message="No drafts waiting. The finalization queue is clear." />
      </template>
      <Column header="Invoice #" body-class="cell-nowrap">
        <template #body="{ data: row }">
          <span v-if="row.invoice_number" class="doc-no">{{ row.invoice_number }}</span>
          <span v-else class="muted">—</span>
        </template>
      </Column>
      <Column header="Customer">
        <template #body="{ data: row }">
          <span class="name">{{ customerNameById[row.customer_id] ?? row.customer_id.slice(0, 8) }}</span>
        </template>
      </Column>
      <Column field="invoice_type" header="Type">
        <template #body="{ data: row }">
          <Tag :value="row.invoice_type" severity="info" />
        </template>
      </Column>
      <Column field="currency" header="Currency" body-class="cell-nowrap cell-muted" />
      <Column header="Amount" body-class="cell-nowrap" :body-style="{ textAlign: 'right' }" :header-style="{ textAlign: 'right' }">
        <template #body="{ data: row }">
          <span class="num">{{ formatAmount(row.amount, row.currency) }}</span>
        </template>
      </Column>
      <Column field="issue_date" header="Issued" body-class="cell-nowrap cell-muted" />
      <Column field="due_date" header="Due" body-class="cell-nowrap" />
      <Column header="Actions" body-class="cell-nowrap">
        <template #body="{ data: row }">
          <div class="actions" @click.stop>
            <Button
              label="View"
              size="small"
              severity="secondary"
              outlined
              @click="openInvoice(row.invoice_id)">
              <template #icon><AppIcon name="eye" /></template>
            </Button>
            <Button
              label="Finalize"
              size="small"
              :loading="finalize.isPending.value"
              @click="finalize.mutate(row.invoice_id)">
              <template #icon><AppIcon name="check" /></template>
            </Button>
            <Button
              label="Void"
              size="small"
              severity="secondary"
              text
              :loading="voidInvoice.isPending.value"
              @click="voidInvoice.mutate(row.invoice_id)">
              <template #icon><AppIcon name="x" /></template>
            </Button>
          </div>
        </template>
      </Column>
    </DataTable>
  </section>
</template>

<style scoped>
.actions { display: flex; gap: 6px; }
.num { font-variant-numeric: tabular-nums; }
.name { font-weight: 500; }
.muted { color: var(--wb-muted-soft); }
:deep(.p-datatable-tbody > tr) { cursor: pointer; }
</style>
