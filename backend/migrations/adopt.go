// AlembicHead is the last Alembic revision of the frozen Python backend. The
// baseline (00001) is that schema, so a database at this head already holds
// everything 00001 would create.
const AlembicHead = "0028_business_npwp"

// ErrNotAdopted stops the server on the production database before goose
// would try to run the baseline over the Alembic schema.
var ErrNotAdopted = errors.New("database has the Alembic schema but no goose history: run `api adopt-baseline`")

// gooseLockID is goose's lock.DefaultLockID, the key db.Migrate's session
// lock takes. Adopt takes the same key so it never runs beside a migration.
const gooseLockID int64 = 4097083626

// gooseTable is created exactly as goose v3 creates its version table for
// Postgres (internal/dialects/postgres.go CreateTable, default table name),
// so a later db.Migrate finds it and only applies what comes after the
// versions recorded in it.
const gooseTable = `CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`

// CheckAdopted is serve's guard before db.Migrate. Goose owns the database
// only once goose_db_version records the baseline (version 1) as applied;
// then, or when the database has no tables at all (goose builds it from the
// baseline), it returns nil. Otherwise goose would run the baseline over an
// existing schema, so it refuses: ErrNotAdopted when alembic_version is there
// (with or without a goose table that lacks the baseline), and an error naming
// the case for tables with goose history lacking the baseline or with no
// history at all.
func CheckAdopted(ctx context.Context, pool *pgxpool.Pool) error {
	var goose, alembic bool
	var tables int64
	err := pool.QueryRow(ctx, `SELECT
			to_regclass('goose_db_version') IS NOT NULL,
			to_regclass('alembic_version') IS NOT NULL,
			(SELECT count(*) FROM pg_class
			 WHERE relnamespace = 'public'::regnamespace AND relkind IN ('r', 'p')
			   AND relname NOT IN ('goose_db_version', 'alembic_version'))`).Scan(&goose, &alembic, &tables)
	if err != nil {
		return fmt.Errorf("check adopted: %w", err)
	}
	baseline := false
	if goose {
		if err := pool.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM goose_db_version WHERE version_id >= 1 AND is_applied)`).Scan(&baseline); err != nil {
			return fmt.Errorf("check adopted: %w", err)
		}
	}
	if baseline {
		return nil
	}
	if alembic {
		return ErrNotAdopted
	}
	if tables > 0 {
		if goose {
			return fmt.Errorf("check adopted: goose_db_version records no baseline but the database already has %d tables: refusing to run the baseline over them", tables)
		}
		return fmt.Errorf("check adopted: database has %d tables but neither goose nor Alembic history: refusing to migrate it", tables)
	}
	return nil
}

// Adopt makes goose the owner of a database built by Alembic at AlembicHead,
// without running the baseline: it records versions 0 and 1 as applied, so
// db.Migrate then applies only the migrations after the baseline. It refuses
// unless goose has no history yet, alembic_version is exactly AlembicHead,
// and the schema is line for line the one the baseline describes
// (testdata/schema-snapshot.sql against testdata/alembic-0028.schema.txt). It
// runs in one transaction under goose's lock key, so a refusal writes nothing.
func Adopt(ctx context.Context, pool *pgxpool.Pool) error {
	tx, err := pool.Begin(ctx)
	if err != nil {
		return fmt.Errorf("adopt: begin: %w", err)
	}
	defer func() { _ = tx.Rollback(context.WithoutCancel(ctx)) }()

	if _, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock($1)`, gooseLockID); err != nil {
		return fmt.Errorf("adopt: lock: %w", err)
	}
	gooseExists, err := checkNoGooseHistory(ctx, tx)
	if err != nil {
		return err
	}
	if err := checkAlembicHead(ctx, tx); err != nil {
		return err
	}
	if err := checkSchema(ctx, tx); err != nil {
		return err
	}
	if !gooseExists {
		if _, err := tx.Exec(ctx, gooseTable); err != nil {
			return fmt.Errorf("adopt: create goose_db_version: %w", err)
		}
	}
	// Version 0 is the row goose writes when it creates the table; version 1
	// is the baseline, already present as Alembic's schema.
	for _, v := range []int64{0, 1} {
		if _, err := tx.Exec(ctx, `INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, $2)`, v, true); err != nil {
			return fmt.Errorf("adopt: record version %d: %w", v, err)
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("adopt: commit: %w", err)
	}
	return nil
}

// checkNoGooseHistory refuses a database goose already has rows for, and
// reports whether its (empty) version table exists.
func checkNoGooseHistory(ctx context.Context, tx pgx.Tx) (bool, error) {
	var exists bool
	if err := tx.QueryRow(ctx, `SELECT to_regclass('goose_db_version') IS NOT NULL`).Scan(&exists); err != nil {
		return false, fmt.Errorf("adopt: %w", err)
	}
	if !exists {
		return false, nil
	}
	var rows int64
	if err := tx.QueryRow(ctx, `SELECT count(*) FROM goose_db_version`).Scan(&rows); err != nil {
		return false, fmt.Errorf("adopt: %w", err)
	}
	if rows > 0 {
		return false, fmt.Errorf("adopt: goose_db_version already has %d rows: the database is already adopted", rows)
	}
	return true, nil
}

func checkAlembicHead(ctx context.Context, tx pgx.Tx) error {
	var exists bool
	if err := tx.QueryRow(ctx, `SELECT to_regclass('alembic_version') IS NOT NULL`).Scan(&exists); err != nil {
		return fmt.Errorf("adopt: %w", err)
	}
	if !exists {
		return errors.New("adopt: no alembic_version table: this is not a database built by the Python backend")
	}
	rows, err := tx.Query(ctx, `SELECT version_num FROM alembic_version ORDER BY version_num`)
	if err != nil {
		return fmt.Errorf("adopt: %w", err)
	}
	versions, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		return fmt.Errorf("adopt: %w", err)
	}
	if len(versions) != 1 || versions[0] != AlembicHead {
		return fmt.Errorf("adopt: alembic_version is %q, want %q: bring the database to that Alembic head first", strings.Join(versions, ","), AlembicHead)
	}
	return nil
}

// checkSchema compares the live schema with the reference description of the
// Alembic head the baseline was made from.
func checkSchema(ctx context.Context, tx pgx.Tx) error {
	query, err := Testdata.ReadFile("testdata/schema-snapshot.sql")
	if err != nil {
		return fmt.Errorf("adopt: %w", err)
	}
	ref, err := Testdata.ReadFile("testdata/alembic-0028.schema.txt")
	if err != nil {
		return fmt.Errorf("adopt: %w", err)
	}
	if len(ref) == 0 {
		return errors.New("adopt: testdata/alembic-0028.schema.txt is empty")
	}
	rows, err := tx.Query(ctx, string(query))
	if err != nil {
		return fmt.Errorf("adopt: schema snapshot: %w", err)
	}
	got, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		return fmt.Errorf("adopt: schema snapshot: %w", err)
	}
	// Function lines hold newlines, so both sides are compared as text and
	// then split the same way for the report.
	live := strings.Join(got, "\n")
	if live == strings.TrimSuffix(string(ref), "\n") {
		return nil
	}
	got = strings.Split(live, "\n")
	want := strings.Split(strings.TrimSuffix(string(ref), "\n"), "\n")
	var b strings.Builder
	b.WriteString("adopt: the schema differs from Alembic " + AlembicHead + " as the baseline describes it")
	onlyIn(&b, "only in this database", got, want)
	onlyIn(&b, "missing from this database", want, got)
	return errors.New(b.String())
}

// onlyIn writes up to 10 lines of from that other lacks.
func onlyIn(b *strings.Builder, label string, from, other []string) {
	in := make(map[string]bool, len(other))
	for _, l := range other {
		in[l] = true
	}
	shown := 0
	for _, l := range from {
		if !in[l] {
			if shown == 10 {
				b.WriteString("\n  ...")
				return
			}
			b.WriteString("\n  " + label + ": " + l)
			shown++
		}
	}
}
