#!/usr/bin/env bash
# Regenerates migrations/00001_baseline.sql and the reference schema
# migrations/testdata/alembic-0028.schema.txt from the Python backend's
# Alembic migrations (backend-python/, frozen at 0028_business_npwp,
# see backend-python/FROZEN.md).
#
# Needs the shared dev stack running (Compose project wenhao-billing): its Postgres
# container runs two scratch databases that this script creates and drops, and
# its backend image runs `alembic upgrade head`.
# The stack's own databases are never touched. Re-run it only if the frozen
# Alembic head changes; the baseline is otherwise not edited by hand.
#
#   1. alembic upgrade head into an empty scratch database
#   2. pg_dump --schema-only --no-owner --no-privileges, cleaned by
#      clean-dump.pl (see its header for what goes) -> 00001_baseline.sql
#   3. the reference schema: migrations/testdata/schema-snapshot.sql run
#      against the Alembic database (TestSchemaMatchesAlembic runs the same
#      query against a goose-migrated database and compares)
#      Seed rows: every table with rows after the upgrade (not alembic_version)
#      is appended as INSERTs; alembic-0028.rows.txt records them for the test.
#   4. a pg_dump-level check: the baseline applied to a second scratch
#      database dumps to the same cleaned text as the Alembic database
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -n "${MSYSTEM:-}" ]]; then export MSYS_NO_PATHCONV=1; root=$(cd .. && pwd -W); else root=$(cd .. && pwd); fi
DB=wenhao-billing-db-1
NETWORK=wenhao-billing_default
IMAGE=wenhao-billing-backend
HEAD=0028_business_npwp
ALEMBIC_DB=wb_go_baseline
GOOSE_DB=wb_go_baseline_goose
work=$(mktemp -d)
trap 'docker exec "$DB" dropdb -U billing --if-exists "$ALEMBIC_DB"; docker exec "$DB" dropdb -U billing --if-exists "$GOOSE_DB"; rm -rf "$work"' EXIT

docker exec "$DB" dropdb -U billing --if-exists "$ALEMBIC_DB"
docker exec "$DB" dropdb -U billing --if-exists "$GOOSE_DB"
docker exec "$DB" createdb -U billing "$ALEMBIC_DB"
docker exec "$DB" createdb -U billing "$GOOSE_DB"

# 1. Alembic, run in the backend image against the scratch database (the sync
#    psycopg driver, as the dev stack's own DATABASE_URL uses).
docker run --rm --network "$NETWORK" \
  -e "DATABASE_URL=postgresql+psycopg://billing:billing@db:5432/${ALEMBIC_DB}" \
  -v "$root/backend-python:/app" -w /app "$IMAGE" alembic upgrade head
read_version=$(docker exec "$DB" psql -U billing -d "$ALEMBIC_DB" -At -c 'select version_num from alembic_version')
[[ "$read_version" == "$HEAD" ]] || { echo "alembic ended at $read_version, not $HEAD" >&2; exit 1; }

# 1b. The tables Alembic's migrations leave with rows (seed data), other than
#     alembic_version. The baseline carries these rows, so a fresh Go database
#     equals a fresh Alembic one.
seed_tables=()
for t in $(docker exec "$DB" psql -U billing -d "$ALEMBIC_DB" -At -c "select tablename from pg_tables where schemaname='public' and tablename <> 'alembic_version' order by 1"); do
  n=$(docker exec "$DB" psql -U billing -d "$ALEMBIC_DB" -At -c "select count(*) from public.\"$t\"")
  if [[ "$n" != 0 ]]; then seed_tables+=("$t"); echo "seed table $t: $n rows"; fi
done
# The same rows as text, one line per row, for TestSeedRowsMatchAlembic.
{
  echo "-- Generated by port/make-baseline.sh: the rows of the tables the Alembic migrations seed."
  echo "SELECT line FROM ("
  sep=""
  for t in "${seed_tables[@]}"; do
    echo "  ${sep}SELECT '$t ' || x::text AS line FROM public.\"$t\" x"
    sep="UNION ALL "
  done
  echo ") s ORDER BY line COLLATE \"C\";"
} > migrations/testdata/rows-snapshot.sql
seed_dump() {
  local args=()
  for t in "${seed_tables[@]}"; do args+=(-t "public.$t"); done
  # Only the INSERTs and sequence positions; pg_dump's SET lines and comments go.
  docker exec "$DB" pg_dump -U billing --data-only --inserts --column-inserts --no-owner --no-privileges "${args[@]}" "$1" |
    grep -E '^(INSERT INTO |SELECT pg_catalog\.setval)' | LC_ALL=C sort
}

# 2. The baseline.
dump() { docker exec "$DB" pg_dump -U billing --schema-only --no-owner --no-privileges "$1" | perl port/clean-dump.pl; }
{
  echo "-- +goose Up"
  echo "-- The Python backend's schema at Alembic head $HEAD (backend-python/FROZEN.md),"
  echo "-- produced by port/make-baseline.sh. An existing database whose alembic_version"
  echo "-- reads that head is stamped as applied instead of running this."
  echo
  dump "$ALEMBIC_DB"
  echo
  echo "-- Rows the Alembic migrations insert (${seed_tables[*]})."
  seed_dump "$ALEMBIC_DB"
  echo
  echo "-- +goose Down"
  echo "-- The baseline is not reversible: it is the schema of a database that holds data."
  echo "SELECT 1/0;"
} > migrations/00001_baseline.sql

# 3. The reference schema.
snapshot() { docker exec -i "$DB" psql -U billing -d "$1" -At -v ON_ERROR_STOP=1 -f - < migrations/testdata/schema-snapshot.sql; }
snapshot "$ALEMBIC_DB" > migrations/testdata/alembic-0028.schema.txt
rows() { docker exec -i "$DB" psql -U billing -d "$1" -At -v ON_ERROR_STOP=1 -f - < migrations/testdata/rows-snapshot.sql; }
rows "$ALEMBIC_DB" > migrations/testdata/alembic-0028.rows.txt

# 4. The same baseline file, applied with psql to the second database, dumps
#    to the same text as the Alembic database (this is pg_dump's view of
#    "the same schema", on top of the catalog snapshot the Go test compares).
sed '/^-- +goose Down/,$d' migrations/00001_baseline.sql | docker exec -i "$DB" psql -U billing -d "$GOOSE_DB" -q -v ON_ERROR_STOP=1 -f - > /dev/null
diff <(dump "$ALEMBIC_DB") <(dump "$GOOSE_DB") > "$work/dump.diff" || { head -40 "$work/dump.diff" >&2; echo "baseline does not reproduce the Alembic schema" >&2; exit 1; }
diff <(snapshot "$ALEMBIC_DB") <(snapshot "$GOOSE_DB") > /dev/null || { echo "baseline snapshot differs from the Alembic schema" >&2; exit 1; }
diff <(rows "$ALEMBIC_DB") <(rows "$GOOSE_DB") > /dev/null || { echo "baseline rows differ from the Alembic database" >&2; exit 1; }
echo "wrote migrations/00001_baseline.sql and migrations/testdata/alembic-0028.{schema,rows}.txt"
